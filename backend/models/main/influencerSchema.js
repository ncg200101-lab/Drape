import mongoose from 'mongoose';

const influencerSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    name: {
      type: String,
      required: true
    },
    email: {
      type: String,
      required: true,
      unique: true
    },
    phone: {
      type: String,
      required: true
    },
    note: {
      type: String
    },
    reglink: {
      type: String
    },
    isConfirmed: {
      type: Boolean,
      default: false
    }
  },
  {
    timestamps: true
  }
);

export default influencerSchema;
