import mongoose from 'mongoose';

const brandStaffSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    firstName: {
      type: String,
      required: true
    },
    lastName: {
      type: String,
      required: true
    },
    email: {
      type: String,
      required: true
    },
    phone: {
      type: String,
      required: true
    },
    address: {
      type: String
    },
    brandName: {
      type: String,
      required: true
    },
    lastLoginAt: {
      type: String
    }
  },
  {
    timestamps: true
  }
);

export default brandStaffSchema;
